"""
test_retargeting_smoke.py — channel-order and channels.json guard tests.

Why this file exists (item 6, executed 2026-11-27): the swap probe
(swap eyeBlinkLeft <-> eyeBlinkRight in CORE32_CHANNEL_NAMES) left the whole
40-test suite GREEN — nothing executed pinned the frozen Core-32 order. The
CI "Golden CRC pin" would catch some drifts, but CI is not running (403), and
a swap of two names the vector generators never address (eyeBlink* pair) is
invisible even to the blob CRCs. These tests close that hole in the EXECUTED
suite:

  T1  test_core32_names_pin               hard-coded canonical pin (any reorder is loud)
  T2  test_channels_json_matches_canon    channels.json idx 0..31 == code NAMES;
                                          32..51 Extended; 52..71 Premium frozen
  T3  test_vectors_regenerate_byte_exact  stored .b64 == regenerated bytes for
                                          all six §8 streams — brings the CI
                                          "Golden CRC pin" into the local suite
  T4  test_coverage_category_matches_equiv  the user contract (genuine_gap ⇒
                                          no arkit_equivalent; redundant ⇒ int < 52)
  T5  test_arkit_equivalent_crossrefs     redundant equivalence points at the
                                          claimed channel NAME, not just any index
  T6  test_wire_semantics_are_declared    mouthClose (+ variants) and
                                          mouthLipsPart declare wire semantics
  T7  test_metahuman_target_null_everywhere  decision (a)
  T8  test_counts_and_contiguity          32/20/20, indices 0..71, coverage counts

Run: python -m unittest test_retargeting_smoke -v
"""
import base64
import json
import pathlib
import unittest

import facecontract_v141 as fc

HERE = pathlib.Path(__file__).resolve().parent
CHANNELS_PATH = HERE / "channels.json"

# ── hard-coded canonical pins (the point of T1: these literals never move) ──
EXPECTED_CORE32 = [
    "eyeBlinkLeft", "eyeBlinkRight", "eyeWideLeft", "eyeWideRight",
    "browDownLeft", "browDownRight", "browInnerUp",
    "jawForward", "jawLeft", "jawRight", "jawOpen",
    "mouthFunnel", "mouthPucker",
    "mouthSmileLeft", "mouthSmileRight",
    "mouthFrownLeft", "mouthFrownRight",
    "mouthStretchLeft", "mouthStretchRight",
    "mouthLowerDownLeft", "mouthLowerDownRight",
    "mouthUpperUpLeft", "mouthUpperUpRight",
    "mouthClose", "mouthPressLeft", "mouthPressRight",
    "cheekPuff", "cheekSquintLeft", "cheekSquintRight",
    "noseSneerLeft", "noseSneerRight", "tongueOut",
]
EXPECTED_EXTENDED20 = [
    "browOuterUpLeft", "browOuterUpRight",
    "eyeLookDownLeft", "eyeLookDownRight",
    "eyeLookInLeft", "eyeLookInRight",
    "eyeLookOutLeft", "eyeLookOutRight",
    "eyeLookUpLeft", "eyeLookUpRight",
    "eyeSquintLeft", "eyeSquintRight",
    "mouthDimpleLeft", "mouthDimpleRight",
    "mouthLeft", "mouthRight",
    "mouthRollLower", "mouthRollUpper",
    "mouthShrugLower", "mouthShrugUpper",
]
EXPECTED_PREMIUM20 = [
    "eyeUpperLidRaiseLeft", "eyeUpperLidRaiseRight",
    "eyeLowerLidLowerLeft", "eyeLowerLidLowerRight",
    "browRaiseLeft", "browRaiseRight",
    "noseDilationLeft", "noseDilationRight",
    "cheekSuckLeft", "cheekSuckRight",
    "cheekRaiserLowerLeft", "cheekRaiserLowerRight",
    "jawChinRaise", "jawChinLower",
    "mouthTightLeft", "mouthTightRight",
    "mouthLipsTogether", "mouthLipsPart",
    "tongueRaise", "tongueLower",
]


class ChannelGuardTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.doc = json.loads(CHANNELS_PATH.read_text(encoding="utf-8"))
        cls.channels = cls.doc["channels"]
        cls.premium = cls.channels[52:]

    # ── T1 ────────────────────────────────────────────────────────────────
    def test_core32_names_pin(self):
        """Any reorder of CORE32_CHANNEL_NAMES must break loudly, even for
        names the vector generators never address (measured: eyeBlink* swap
        was invisible to the whole pre-existing suite)."""
        self.assertEqual(fc.CORE32_CHANNEL_NAMES, EXPECTED_CORE32)
        self.assertEqual(fc.NAME_TO_INDEX["jawOpen"], 10)
        self.assertEqual(fc.NAME_TO_INDEX["mouthClose"], 23)
        self.assertEqual(fc.NAME_TO_INDEX["mouthPressLeft"], 24)
        self.assertEqual(fc.NAME_TO_INDEX["tongueOut"], 31)

    # ── T2 ────────────────────────────────────────────────────────────────
    def test_channels_json_matches_canon(self):
        self.assertEqual([c["name"] for c in self.channels[:32]],
                         fc.CORE32_CHANNEL_NAMES,
                         "channels.json Core-32 order diverged from the code canon")
        self.assertEqual([c["name"] for c in self.channels[32:52]],
                         EXPECTED_EXTENDED20)
        self.assertEqual([c["name"] for c in self.channels[52:]],
                         EXPECTED_PREMIUM20)

    # ── T3 ────────────────────────────────────────────────────────────────
    def test_vectors_regenerate_byte_exact(self):
        """Every §8 stream regenerated from the contract must be byte-identical
        to the stored locked .b64 vector. This pins NAME_TO_INDEX-dependent
        generators (speech_to_idle.fc14) AND the whole-blob CRCs locally —
        the CI golden pin, executed even while CI is not running."""
        for name, blob in fc.build_fc14_streams():
            stored = base64.b64decode(
                (HERE / "test_vectors" / f"{name}.b64").read_text())
            self.assertEqual(blob, stored,
                             f"{name}: regenerated bytes diverge from the "
                             "locked .b64 vector")

    # ── T4 (the user contract, verbatim semantics) ────────────────────────
    def test_coverage_category_matches_equiv(self):
        """genuine_gap ⇒ no arkit_equivalent; redundant ⇒ equivalence must
        point to Level 1."""
        for ch in self.premium:
            cov = ch.get("coverage")
            self.assertIn(
                cov, {"genuine_gap", "composition_alternative",
                      "redundant_with_arkit"},
                f"{ch['name']}: unknown coverage {cov!r}")
            if cov == "genuine_gap":
                self.assertIsNone(
                    ch.get("arkit_equivalent"),
                    f"{ch['name']}: genuine_gap but arkit_equivalent set")
            if cov == "redundant_with_arkit":
                self.assertIsInstance(
                    ch.get("arkit_equivalent"), int,
                    f"{ch['name']}: redundant requires arkit_equivalent index")
                self.assertLess(
                    ch["arkit_equivalent"], 52,
                    f"{ch['name']}: arkit_equivalent must be a Level-1 index")

    # ── T5 ────────────────────────────────────────────────────────────────
    def test_arkit_equivalent_crossrefs(self):
        for ch in self.premium:
            eq = ch.get("arkit_equivalent")
            if isinstance(eq, int):
                claimed = ch.get("arkit_equivalent_name")
                self.assertIsNotNone(
                    claimed, f"{ch['name']}: arkit_equivalent without a name")
                self.assertEqual(
                    self.channels[eq]["name"], claimed,
                    f"{ch['name']}: arkit_equivalent {eq} points at "
                    f"{self.channels[eq]['name']!r}, claimed {claimed!r}")

    # ── T6 ────────────────────────────────────────────────────────────────
    def test_wire_semantics_are_declared(self):
        by_name = {c["name"]: c for c in self.channels}
        mc = by_name["mouthClose"]
        self.assertTrue(mc.get("wire_semantics"),
                        "mouthClose: wire_semantics must be declared")
        self.assertIn("arkit-canonical", mc.get("semantic_variants", []),
                      "mouthClose: semantic_variants missing arkit-canonical")
        self.assertIn("nvidia-a2f", mc.get("semantic_variants", []),
                      "mouthClose: semantic_variants missing nvidia-a2f")
        self.assertTrue(by_name["mouthLipsPart"].get("wire_semantics"),
                        "mouthLipsPart: wire_semantics must be declared")

    # ── T7 ────────────────────────────────────────────────────────────────
    def test_metahuman_target_null_everywhere(self):
        for ch in self.channels:
            self.assertIsNone(
                ch.get("metahuman_target"),
                f"{ch['name']}: metahuman_target must be null (decision (a)); "
                "rig mapping is client-side (RETARGETING.md)")

    # ── T8 ────────────────────────────────────────────────────────────────
    def test_counts_and_contiguity(self):
        self.assertEqual(len(self.channels), 72)
        self.assertEqual([c["facecontract_idx"] for c in self.channels],
                         list(range(72)))
        levels = [sum(1 for c in self.channels if c["level"] == lv)
                  for lv in (0, 1, 2)]
        self.assertEqual(levels, [32, 20, 20])
        self.assertEqual(
            self.doc["premium_coverage_counts"],
            {"genuine_gap": 10, "genuine_gap_low_priority": 6,
             "composition_alternative": 4, "redundant_with_arkit": 6})
        self.assertTrue(self.doc["metahuman_policy"].startswith(
            "metahuman_target is null everywhere"))


if __name__ == "__main__":
    unittest.main(verbosity=2)
